const assert=require('node:assert/strict');
const api=require('../cognitive-label.js');
const key=api.values[0];
let tag={ratings:{[key]:{level:'3 · Expliqué mis razones',evidence:''}}};
assert.equal(api.ratings(tag)[0].supported,true);
assert.equal(api.ratings(tag)[0].level,'3');
tag.ratings[key].evidence='Comparé las fuentes y rechacé una afirmación.';
assert.equal(api.ratings(tag)[0].supported,true);
const state={activityName:'Prueba',_cognitiveTags:{test:{...tag,aiFunction:'Ayudante',relation:'Soberanía cognitiva',relationEvidence:'Decidí con criterio'}}};
const steps=[{id:'test',title:'Prueba'}];
const html=api.render(state,steps);
assert(html.includes('★★★☆☆'));
assert(!html.includes('Estado de revisión del aprendizaje'));
assert(html.includes('Soberanía cognitiva'));
assert(!html.includes('0%'));
assert.equal(api.build({_cognitiveTags:{}},steps).length,0);
assert(api.render({...state,activityName:'<script>alert(1)</script>'},steps).includes('&lt;script&gt;'));
console.log('PASS: levels require evidence, justified relation, stars, pending understanding, safe rendering');
